static int
kat_sha256(void)
{
	unsigned char out[32];

	if (mbedtls_sha256((const unsigned char *)"abc", 3, out, 0) != 0)
		return -1;
	return memcmp(out, sha256_abc, sizeof(sha256_abc)) == 0 ? 0 : -1;
}

static int
kat_gcm(void)
{
	mbedtls_gcm_context gcm;
	unsigned char ct[16], tag[16], pt[16];
	int r;

	mbedtls_gcm_init(&gcm);
	r = mbedtls_gcm_setkey(&gcm, MBEDTLS_CIPHER_ID_AES, gcm_key,
	    sizeof(gcm_key) * 8);
	if (r == 0)
		r = mbedtls_gcm_crypt_and_tag(&gcm, MBEDTLS_GCM_ENCRYPT,
		    sizeof(gcm_pt), gcm_iv, sizeof(gcm_iv), NULL, 0, gcm_pt,
		    ct, sizeof(tag), tag);
	if (r == 0 && (memcmp(ct, gcm_ct, sizeof(ct)) != 0 ||
	    memcmp(tag, gcm_tag, sizeof(tag)) != 0))
		r = -1;
	if (r == 0)
		r = mbedtls_gcm_auth_decrypt(&gcm, sizeof(gcm_ct), gcm_iv,
		    sizeof(gcm_iv), NULL, 0, gcm_tag, sizeof(gcm_tag), gcm_ct,
		    pt);
	if (r == 0 && memcmp(pt, gcm_pt, sizeof(pt)) != 0)
		r = -1;
	mbedtls_gcm_free(&gcm);
	return r == 0 ? 0 : -1;
}

static int
kat_rsa(void)
{
	mbedtls_pk_context pk;
	int r;

	mbedtls_pk_init(&pk);
	r = mbedtls_pk_setup(&pk, mbedtls_pk_info_from_type(MBEDTLS_PK_RSA));
	if (r == 0)
		r = mbedtls_rsa_import_raw(mbedtls_pk_rsa(pk), rsa_n,
		    sizeof(rsa_n), NULL, 0, NULL, 0, NULL, 0, rsa_e,
		    sizeof(rsa_e));
	if (r == 0)
		r = mbedtls_rsa_complete(mbedtls_pk_rsa(pk));
	if (r == 0)
		r = mbedtls_pk_verify(&pk, MBEDTLS_MD_SHA256, rsa_hash,
		    sizeof(rsa_hash), rsa_sig, sizeof(rsa_sig));
	if (r == 0)
		r = mbedtls_pk_verify(&pk, MBEDTLS_MD_SHA256, rsa_hash,
		    sizeof(rsa_hash), rsa_sig, sizeof(rsa_sig) - 1) == 0 ? -1 : 0;
	mbedtls_pk_free(&pk);
	return r == 0 ? 0 : -1;
}

int
rump_tls_kat(void)
{
	if (kat_sha256() != 0) {
		printf("tls: FAILED (sha256)\n");
		return -1;
	}
	if (kat_gcm() != 0) {
		printf("tls: FAILED (aes-gcm)\n");
		return -1;
	}
	if (kat_rsa() != 0) {
		printf("tls: FAILED (rsa)\n");
		return -1;
	}
	printf("tls: KATs ok (sha256 + aes-gcm + rsa)\n");
	return 0;
}
